async def send_neuro_jurist_posts():
    """Отправляет 12 новостей в чат НейроЮрист."""
    client = TelegramClient(SESSION_FILE, API_ID, API_HASH)
    await client.start()
    print("[INFO] Подключено к Telegram")
    
    try:
        entity = await client.get_entity(NEURO_JURIST_CHAT_INVITE)
    except Exception as e:
        print(f"[WARN] Не удалось получить entity по инвайту напрямую: {e}")
        async for dialog in client.iter_dialogs():
            if "нейроюрист" in dialog.name.lower() or "l_1s3JcOKLI4OGI0" in str(dialog.entity):
                entity = dialog.entity
                print(f"[INFO] Нашли чат: {dialog.name}")
                break
        else:
            print("[ERROR] Чат НейроЮрист не найден. Пробуем вступить...")
            result = await client(JoinChannelRequest(NEURO_JURIST_CHAT_INVITE))
            entity = result.chats[0]
    
    print(f"[INFO] Чат найден: {entity}")
    print(f"[INFO] Отправляем {len(POSTS)} новостей...")
    
    for i, post in enumerate(POSTS, 1):
        try:
            await client.send_message(entity, post, parse_mode='md')
            print(f"[OK] Отправлен post {i}/{len(POSTS)}")
            if i < len(POSTS):
                time.sleep(3)
        except FloodWaitError as e:
            print(f"[FLOOD] Ждём {e.seconds} секунд...")
            time.sleep(e.seconds + 2)
            await client.send_message(entity, post, parse_mode='md')
            print(f"[OK] Отправлен post {i}/{len(POSTS)} (после паузы)")
        except Exception as e:
            print(f"[ERROR] Ошибка при отправке поста {i}: {e}")
    
    print("[DONE] Все новости отправлены!")
    await client.disconnect()

if __name__ == "__main__":
    asyncio.run(send_neuro_jurist_posts())
